import mongoose from 'mongoose';
import { ReturnItem } from './return-item.model.js';

const { Schema, model } = mongoose;

const returnSchema = new Schema(
  {
    returnNumber: { type: String, required: true, unique: true },
    orderId: { type: Schema.Types.ObjectId, ref: 'Order', required: true, index: true },
    vendorOrderId: { type: Schema.Types.ObjectId, ref: 'VendorOrder', default: null, index: true },
    customerId: { type: Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    vendorId: { type: Schema.Types.ObjectId, ref: 'Vendor', required: true, index: true },
    type: {
      type: String,
      enum: ['RETURN', 'REPLACEMENT'],
      default: 'RETURN',
      index: true,
    },
    reason: { type: String, default: 'DAMAGED_OR_DEFECTIVE' },
    description: { type: String, default: null },
    status: {
      type: String,
      enum: [
        'REQUESTED',
        'UNDER_REVIEW',
        'APPROVED',
        'REJECTED',
        'PICKUP_SCHEDULED',
        'IN_TRANSIT',
        'RECEIVED',
        'RETURN_RECEIVED',
        'INSPECTION_PENDING',
        'INSPECTING',
        'INSPECTION_PASSED',
        'INSPECTION_FAILED',
        'DISPOSITION_PENDING',
        'DISPOSITION_COMPLETED',
        'DISPUTED',
        'APPROVED_FOR_REFUND',
        'REFUND_PENDING',
        'REFUND_PROCESSING',
        'REFUNDED',
        'REFUND_FAILED',
        'MANUAL_PAYOUT_PENDING',
        'MANUAL_PAYOUT_PROCESSING',
        'REPLACEMENT_PENDING',
        'REPLACEMENT_SHIPPED',
        'REPLACEMENT_DELIVERED',
        'REJECTED_AFTER_INSPECTION',
        'COMPLETED',
        'CLOSED',
        'CANCELLED',
      ],
      default: 'REQUESTED',
      index: true,
    },
    items: [{ type: Schema.Types.ObjectId, ref: 'ReturnItem', default: [] }],
    evidenceImages: [{ type: String, trim: true }],
    refundDetails: { type: Object, default: null },
    payoutDetails: {
      method: { type: String, enum: ['UPI', 'BANK_ACCOUNT', null], default: null },
      upiId: { type: String, trim: true, default: null },
      accountHolderName: { type: String, trim: true, default: null },
      accountNumber: { type: String, trim: true, default: null },
      maskedAccountNumber: { type: String, trim: true, default: null },
      ifscCode: { type: String, trim: true, default: null },
      bankName: { type: String, trim: true, default: null },
      submittedAt: { type: Date, default: null },
    },
    manualPayout: {
      status: {
        type: String,
        enum: ['NOT_REQUIRED', 'PENDING_DETAILS', 'PAYOUT_REQUIRED', 'PROCESSING', 'COMPLETED', 'FAILED'],
        default: 'NOT_REQUIRED',
      },
      reference: { type: String, trim: true, default: null },
      paidAt: { type: Date, default: null },
      paidBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      failureReason: { type: String, trim: true, default: null },
      notes: { type: String, trim: true, default: null },
    },
    idempotencyKey: { type: String, default: null, index: true },
    requestedAt: { type: Date, default: Date.now },
    approvedAt: { type: Date, default: null },
    rejectedAt: { type: Date, default: null },
    receivedAt: { type: Date, default: null },
    receivedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    reviewedAt: { type: Date, default: null },
    reviewedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    completedAt: { type: Date, default: null },
    inspection: {
      inspectedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      inspectedAt: { type: Date, default: null },
      result: { type: String, enum: ['PASS', 'FAIL', 'PASSED', 'FAILED', 'PARTIAL', null], default: null },
      condition: {
        type: String,
        enum: [
          'INTACT',
          'UNUSED',
          'GOOD',
          'USED',
          'DAMAGED',
          'DEFECTIVE',
          'TAG_MISSING',
          'WRONG_ITEM',
          'MISSING_PARTS',
          'TAMPERED',
          'OTHER',
          null,
        ],
        default: null,
      },
      itemCondition: {
        type: String,
        enum: [
          'INTACT',
          'UNUSED',
          'GOOD',
          'USED',
          'DAMAGED',
          'DEFECTIVE',
          'TAG_MISSING',
          'WRONG_ITEM',
          'MISSING_PARTS',
          'TAMPERED',
          'OTHER',
          null,
        ],
        default: null,
      },
      conditionNotes: { type: String, trim: true, default: null },
      notes: { type: String, trim: true, default: null },
      proofImages: [{ type: String, trim: true }],
      evidence: [{ type: String, trim: true }],
      packagingCondition: {
        type: String,
        enum: ['INTACT', 'DAMAGED', 'OPENED', 'MISSING', 'OTHER', null],
        default: null,
      },
      accessoriesComplete: { type: Boolean, default: null },
      authenticityCondition: {
        type: String,
        enum: ['AUTHENTIC', 'MISMATCH', 'SUSPECTED_COUNTERFEIT', 'TAMPERED', 'OTHER', null],
        default: null,
      },
      totalReturnedQuantity: { type: Number, default: 0 },
      totalAcceptedQuantity: { type: Number, default: 0 },
      totalRejectedQuantity: { type: Number, default: 0 },
      items: [
        {
          returnItemId: { type: Schema.Types.ObjectId, ref: 'ReturnItem', default: null },
          variantId: { type: Schema.Types.ObjectId, ref: 'ProductVariant', default: null },
          returnedQuantity: { type: Number, default: 0 },
          acceptedQuantity: { type: Number, default: 0 },
          rejectedQuantity: { type: Number, default: 0 },
          condition: { type: String, default: null },
          itemCondition: { type: String, default: null },
          notes: { type: String, default: null },
          evidence: [{ type: String, trim: true }],
          authenticityCondition: { type: String, default: null },
        },
      ],
    },
    dispute: {
      disputedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      disputedAt: { type: Date, default: null },
      reason: {
        type: String,
        enum: [
          'WRONG_ITEM_RETURNED',
          'ITEM_USED',
          'ITEM_DAMAGED_BY_CUSTOMER',
          'MISSING_PARTS',
          'TAG_REMOVED',
          'DIFFERENT_PRODUCT',
          'AUTHENTICITY_MISMATCH',
          'SUSPECTED_COUNTERFEIT',
          'TAMPERED',
          'OTHER',
          null,
        ],
        default: null,
      },
      description: { type: String, trim: true, default: null },
      evidence: [{ type: String, trim: true }],
      status: {
        type: String,
        enum: ['PENDING_ADMIN_REVIEW', 'RESOLVED_SELLER', 'RESOLVED_CUSTOMER', 'MORE_INFO_REQUESTED', 'RESOLVED'],
        default: 'PENDING_ADMIN_REVIEW',
      },
      decision: {
        type: String,
        enum: ['UPHOLD_CUSTOMER', 'UPHOLD_SELLER', 'REQUEST_MORE_INFO', null],
        default: null,
      },
      decisionReason: { type: String, default: null },
      decidedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      decidedAt: { type: Date, default: null },
      adminNotes: { type: String, default: null },
    },
    resolution: {
      action: {
        type: String,
        enum: ['RETURN_REFUND', 'REPLACEMENT', 'REJECT_RETURN', null],
        default: null,
      },
      resolvedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      resolvedAt: { type: Date, default: null },
      notes: { type: String, trim: true, default: null },
      calculatedRefundAmount: { type: Number, default: null },
    },
    disposition: {
      status: {
        type: String,
        enum: ['PENDING', 'PROCESSING', 'COMPLETED', null],
        default: null,
      },
      disposedAt: { type: Date, default: null },
      disposedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      claimedAt: { type: Date, default: null },
      claimedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
      notes: { type: String, trim: true, default: null },
      totalRestockableQuantity: { type: Number, default: 0, min: 0 },
      totalNonRestockableQuantity: { type: Number, default: 0, min: 0 },
      items: [
        {
          returnItemId: { type: Schema.Types.ObjectId, ref: 'ReturnItem', required: true },
          variantId: { type: Schema.Types.ObjectId, ref: 'ProductVariant', default: null },
          productId: { type: Schema.Types.ObjectId, ref: 'Product', default: null },
          returnedQuantity: { type: Number, default: 0, min: 0 },
          acceptedQuantity: { type: Number, default: 0, min: 0 },
          rejectedQuantity: { type: Number, default: 0, min: 0 },
          restockableQuantity: { type: Number, default: 0, min: 0 },
          nonRestockableQuantity: { type: Number, default: 0, min: 0 },
          disposition: {
            type: String,
            enum: [
              'RESTOCKABLE',
              'DAMAGED',
              'DEFECTIVE',
              'UNSALEABLE',
              'MISSING_PARTS',
              'WRONG_ITEM',
              'AUTHENTICITY_HOLD',
              null,
            ],
            default: 'RESTOCKABLE',
          },
          reason: { type: String, trim: true, default: null },
          restocked: { type: Boolean, default: false },
          restockedAt: { type: Date, default: null },
        },
      ],
    },
    statusHistory: [
      {
        status: { type: String, required: true },
        changedAt: { type: Date, default: Date.now },
        changedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
        actorType: { type: String, enum: ['CUSTOMER', 'VENDOR', 'ADMIN', 'SYSTEM'], default: 'SYSTEM' },
        notes: { type: String, default: null },
      },
    ],
  },
  { timestamps: true },
);

returnSchema.index({ orderId: 1, vendorOrderId: 1 });
returnSchema.index({ customerId: 1, createdAt: -1 });
returnSchema.index({ status: 1, createdAt: -1 });
returnSchema.index(
  { customerId: 1, idempotencyKey: 1 },
  { unique: true, partialFilterExpression: { idempotencyKey: { $type: 'string', $gt: '' } } },
);

export const Return = model('Return', returnSchema);
export { ReturnItem };
